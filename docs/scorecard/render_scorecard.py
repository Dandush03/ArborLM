"""Render the ArborLM progress scorecard.

Reads docs/scorecard/scorecard.toml and writes docs/scorecard/scorecard.svg and the section of
README.md between the scorecard markers. With --check it writes nothing and exits 1 when either
output differs from what the data file gives. Standard library only.
"""

from __future__ import annotations

import sys
import tomllib
from html import escape
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
DATA = HERE / "scorecard.toml"
SVG = HERE / "scorecard.svg"
README = ROOT / "README.md"
START = "<!-- scorecard:start (generated by docs/scorecard/render_scorecard.py; do not edit) -->"
END = "<!-- scorecard:end -->"

WIDTH = 1000
PAD = 28
ROW = 104
TOP = 26
FOOT = 44
GREEN, ORANGE, SLATE = "#3f8f4f", "#d9822b", "#6b7a99"


def load() -> dict:
    data = tomllib.loads(DATA.read_text(encoding="utf-8"))
    rows = data.get("row", [])
    if not rows:
        raise SystemExit("scorecard.toml has no rows")
    for r in rows:
        if not (isinstance(r["score"], int) and 0 <= r["score"] <= 10):
            raise SystemExit(f"score of {r['title']!r} must be an integer from 0 to 10")
        for key in ("title", "note", "next"):
            if not str(r[key]).strip():
                raise SystemExit(f"{key} of {r['title']!r} is empty")
        if not r["evidence"]:
            raise SystemExit(f"{r['title']!r} cites no evidence")
    return data


def colour(score: int) -> str:
    return GREEN if score >= 7 else ORANGE if score >= 4 else SLATE


def render_svg(data: dict) -> str:
    rows = data["row"]
    height = TOP + ROW * len(rows) + FOOT
    track = WIDTH - 2 * PAD
    font = "-apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif"
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height}" '
        f'viewBox="0 0 {WIDTH} {height}" role="img" '
        f'aria-label="ArborLM progress scorecard, updated {escape(data["updated"])}">',
        f'<rect width="{WIDTH}" height="{height}" rx="14" fill="#0f0f10"/>',
        f'<g font-family="{font}">',
    ]
    for i, r in enumerate(rows):
        y = TOP + i * ROW
        fill = max(0, round(track * r["score"] / 10))
        out += [
            f'<text x="{PAD}" y="{y + 22}" fill="#f2f2f2" font-size="19" font-weight="600">'
            f"{escape(r['title'])}</text>",
            f'<text x="{WIDTH - PAD}" y="{y + 22}" fill="#f2f2f2" font-size="19" '
            f'text-anchor="end">{r["score"]}/10</text>',
            f'<rect x="{PAD}" y="{y + 36}" width="{track}" height="8" rx="4" fill="#262626"/>',
            f'<rect x="{PAD}" y="{y + 36}" width="{fill}" height="8" rx="4" '
            f'fill="{colour(r["score"])}"/>',
            f'<text x="{PAD}" y="{y + 70}" fill="#c9c9c9" font-size="15">'
            f"{escape(r['note'])}</text>",
        ]
    foot = f"Working estimate, not a registered result. Updated {data['updated']}: {data['basis']}."
    out += [
        f'<text x="{PAD}" y="{height - 18}" fill="#8a8a8a" font-size="13">{escape(foot)}</text>',
        "</g>",
        "</svg>",
        "",
    ]
    return "\n".join(out)


def render_section(data: dict) -> str:
    lines = [
        START,
        "",
        "![ArborLM progress scorecard](docs/scorecard/scorecard.svg)",
        "",
        "The scores are the research lead's working estimate of how close each requirement of the "
        "target architecture is to being met. They are a planning aid: they are not registered "
        "results and not success claims. The evidence column quotes registered labels. "
        f"Scale: {data['scale']}. Updated {data['updated']} ({data['basis']}). "
        "Source: [`docs/scorecard/scorecard.toml`](docs/scorecard/scorecard.toml).",
        "",
        "| Requirement | Score | Registered evidence | What would move it |",
        "|---|---|---|---|",
    ]
    for r in data["row"]:
        evidence = "<br>".join(e.replace("|", "\\|") for e in r["evidence"])
        nxt = r["next"].replace("|", "\\|")
        lines.append(f"| {r['title']} | {r['score']}/10 | {evidence} | {nxt} |")
    lines += ["", END]
    return "\n".join(lines)


def readme_with(section: str) -> str:
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit("README.md has no scorecard markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + section + tail


def main(argv: list[str]) -> int:
    data = load()
    svg, readme = render_svg(data), readme_with(render_section(data))
    if "--check" in argv:
        stale = [
            str(p.relative_to(ROOT))
            for p, want in ((SVG, svg), (README, readme))
            if not p.exists() or p.read_text(encoding="utf-8") != want
        ]
        if stale:
            print("out of step with docs/scorecard/scorecard.toml: " + ", ".join(stale))
            return 1
        print("scorecard is in step")
        return 0
    SVG.write_text(svg, encoding="utf-8")
    README.write_text(readme, encoding="utf-8")
    print(f"wrote {SVG.relative_to(ROOT)} and the scorecard section of README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
