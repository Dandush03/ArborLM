"""M3 / M4 / M8 re-check in a throwaway source-only clone (made with the implementer's e2e.make_clone), test seeds only (P10S1_TEST_SEEDS=1: p10s1-test-0..4,
seed bases 921001-921401), tiny DRY sizes, synthetic backbone. Nothing is written into the worktree; the clone is deleted at the end; logs are kept in <scratch>/r4-logs.

A. `registered gates` on a clean clone with no freeze plan (freeze commit = HEAD): refused?
B. The worker entry point: with a SELF-MADE plan and its digest typed on the command line, `work gates --mode registered` and `work train --mode registered` run on the
   five generated test draws, with no freeze, no freeze commit, no check_preconditions, no Decision 2 and no ledger. (Under the switch only test seeds can be touched;
   without the switch the same commands would read the registered draws generated by the allowed pre-freeze `generate`.)
C. Commit checks as pure calls on the clone: check_preconditions with a non-freeze ancestor commit; require_decision_2 with the wrong commit, an abbreviated hash,
   an uncommitted file, and a file that names the commit but records no approval.

Run (worktree root): PYTHONPATH=. uv run --locked python docs/reviews/p10s1-implementation-audit-2026-11-15/recheck/r4_clone_probes.py <scratch-dir>
Claude (Opus 5.5) review; Astra review: NOT_PERFORMED; not a human approval.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

from arborlm.io import file_sha256
from studies.p10s1 import core, e2e
from studies.p10s1 import frozen as fz
from studies.p10s1 import stages as S

scratch = Path(sys.argv[1]).resolve()
work = scratch / "r4"
if work.exists():
    shutil.rmtree(work)
work.mkdir(parents=True)
clone, run = work / "clone", work / "run"
logs = scratch / "r4-logs"
logs.mkdir(exist_ok=True)
OUT: dict = {"steps": []}
env = e2e.environment()  # P10S1_TEST_SEEDS=1, current interpreter, no sync


def sh(name, argv, cwd=None):
    done = subprocess.run(argv, cwd=cwd or clone, env=env, capture_output=True, check=False)  # noqa: S603
    (logs / f"{len(OUT['steps']):02d}-{name}.log").write_bytes(b"$ " + " ".join(argv).encode() + b"\n--- stdout\n" + done.stdout + b"\n--- stderr\n" + done.stderr)
    last = (done.stderr.decode().strip().splitlines() or [""])[-1][:300]
    OUT["steps"].append({"step": name, "exit": done.returncode, "stderr_last": last})
    return done.returncode


def git(*argv):
    done = subprocess.run(["git", *e2e.GIT_IDENTITY, "-C", str(clone), *argv], capture_output=True, check=True)  # noqa: S603, S607
    return done.stdout.decode().strip()


def stages(*argv):
    return [sys.executable, "-m", "studies.p10s1.stages", *argv]


try:
    e2e.make_clone(core.repo_root(), clone)
    git("add", "-A")
    git("commit", "--quiet", "--allow-empty", "-m", "r4: code")
    c0 = git("rev-parse", "HEAD")
    sh("set-generation-cap", stages("set-generation-cap", "--generation-seconds", "600"))
    git("add", "-A")
    git("commit", "--quiet", "-m", "r4: generation cap")
    c1 = git("rev-parse", "HEAD")
    sh("generate.sh (five test draws)", ["sh", "studies/p10s1/launch/generate.sh", str(run), c1])
    OUT["draws"] = sorted(p.name for p in (run / "draws").iterdir()) if (run / "draws").is_dir() else []
    # A
    sh("A: registered gates, no freeze plan, freeze commit = HEAD", stages("registered", "gates", "--run-dir", str(run), "--freeze-commit", c1))
    # B: the worker entry point with a self-made plan
    plan = work / "self-made-plan.json"
    fro = fz.Frozen.build(core.Plan(seed_block_draws=(1,), unit=S.DRY_UNIT), fz.default_cpu_table())
    plan.write_text(json.dumps({"frozen": fro.as_json()}))
    digest = file_sha256(plan)
    common = ["--mode", "registered", "--run-dir", str(run), "--freeze-plan", str(plan), "--freeze-plan-sha256", digest]
    sh("B1: work gates --mode registered with a self-made plan", stages("work", "gates", *common))
    OUT["gates_json_written"] = (run / "gates.json").is_file()
    label = next(c.label for c in core.registered_cells(fro.plan, dense_rates=fro.dense_rates) if c.kind == "P" and c.arm == "F-OQ" and c.draw == 1 and c.slots == 4096)
    sh("B2: work train --mode registered with a self-made plan", stages("work", "train", *common, "--labels", label))
    cell = core.cell_dir(run, label)
    OUT["trained_cell_record"] = sorted(p.name for p in cell.iterdir()) if cell.is_dir() else None
    tr = cell / "train.json"
    if tr.is_file():
        rec = json.loads(tr.read_text())
        OUT["trained_cell_mode_and_status"] = {k: rec.get(k) for k in ("status", "mode", "seed_set", "label")}
    OUT["ledger_files_in_clone"] = sorted(str(p.relative_to(clone)) for p in (clone / "experiments").glob("*ledger*")) if (clone / "experiments").is_dir() else []
    # C: commit checks as pure calls
    def refusal(fn, *a):
        try:
            fn(*a)
            return "PASSED"
        except Exception as exc:  # noqa: BLE001
            return f"refused: {str(exc)[:200]}"

    OUT["C1 check_preconditions(freeze=c0, config changed after c0)"] = refusal(S.check_preconditions, "registered", clone, c0)
    (clone / "studies" / "p10s1" / "freeze" / "plan.json").write_text("{}\n")  # a stand-in freeze file (not a valid plan; only the commit checks are probed)
    git("add", "-A")
    git("commit", "--quiet", "-m", "r4: stand-in freeze")
    c2 = git("rev-parse", "HEAD")
    OUT["C2 check_preconditions(freeze=c1, studies changed after c1)"] = refusal(S.check_preconditions, "registered", clone, c1)
    OUT["C3 check_preconditions(freeze=c2)"] = refusal(S.check_preconditions, "registered", clone, c2)
    dec = clone / "results" / "p10s1-freeze-r4" / "DECISION_2.md"
    dec.parent.mkdir(parents=True)
    dec.write_text(f"Decision 2: freeze commit {c2}\n")
    OUT["C4 check_preconditions(freeze=c2) with Decision 2 uncommitted"] = refusal(S.check_preconditions, "registered", clone, c2)
    OUT["C5 require_decision_2(c2) with the file uncommitted"] = refusal(S.require_decision_2, clone, c2)
    git("add", "-A")
    git("commit", "--quiet", "-m", "r4: decision 2")
    c3 = git("rev-parse", "HEAD")
    OUT["C6 require_decision_2(c2)"] = refusal(S.require_decision_2, clone, c2)
    OUT["C7 require_decision_2(c3 = the Decision 2 commit, not the freeze)"] = refusal(S.require_decision_2, clone, c3)
    OUT["C8 check_preconditions(c3) (studies equal at c3 and HEAD)"] = refusal(S.check_preconditions, "registered", clone, c3)
    dec.write_text(f"Decision 2: freeze commit {c2[:12]}\n")
    git("add", "-A")
    git("commit", "--quiet", "-m", "r4: abbreviated")
    OUT["C9 require_decision_2(c2) when the file holds only a 12-character hash"] = refusal(S.require_decision_2, clone, c2)
    dec.write_text(f"NOT APPROVED. The lead declines the registered run of freeze commit {c2}.\n")
    git("add", "-A")
    git("commit", "--quiet", "-m", "r4: declined")
    OUT["C10 require_decision_2(c2) when the file records a refusal"] = refusal(S.require_decision_2, clone, c2)
    OUT["commits"] = {"c0 code": c0, "c1 generation cap": c1, "c2 stand-in freeze": c2, "c3 decision 2": c3}
except Exception as exc:  # noqa: BLE001
    OUT["error"] = f"{type(exc).__name__}: {exc}"
finally:
    shutil.rmtree(work, ignore_errors=True)
json.dump(OUT, sys.stdout, indent=1, default=str)
print()
