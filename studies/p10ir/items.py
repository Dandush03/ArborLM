from . import core, gates, reads, sealed, stages_io

SYNTHETIC_CORPUS = bytes((i * 7 + 3) % 256 for i in range(p9core.CORPUS_ROW_BYTES * 64))
PARENT = p9core.PRIMARY_PARENT
STAGE_RUN = {core.STAGE_A1: "a1", core.STAGE_A2: "a2"}


@dataclass
class Ctx:
    """Where a run reads and writes. ``s1_run_dir`` holds P10-S1's cells (A1 and the rehearsal's miniature run); ``run_dir`` is this study's. ``run_sealed`` allows gate 3 (the registered A1 after Decision 2, and
    rehearsal-made records; never the rehearsal on the registered checkpoints)."""

    mode: str
    run_dir: Path
    s1_run_dir: Path | None
    experiments_root: Path | None
    synthetic: bool = False
    run_sealed: bool = False
    config_path: Path | None = None
    manifests: dict[str, Path] = field(default_factory=dict)
    sizes: dict[str, int] = field(default_factory=lambda: {"table_facts": s1core.FACT_TABLE, "unseen": s1core.UNSEEN_FACTS})

    def cfg(self) -> Any:
        return core.load_config(self.config_path)

    def snapshot_dir(self, item: dict[str, Any]) -> Path:
        root = self.s1_run_dir if item["checkpoint_root"] == "s1" else self.run_dir / "A2" / "train"
        if root is None:
            raise ValueError("no checkpoint root for this item")
        return root / "cells" / item["cell"] / "snapshots" / s1core.snapshot_stem(item["update"])

    def manifest_path(self, item: dict[str, Any]) -> Path | None:
        return self.manifests.get(item["seed_name"])


# --- data, backbone, model ---------------------------------------------------------------------------------------------------------------------
@functools.cache
def _build_data(name: str, base: int, table: int, unseen: int, corpus_key: str, corpus: bytes) -> data_mod.StudyData:
    seeds = s1core.seed_set(name, base)
    return data_mod.build_study_data(seeds, corpus, sizes=data_mod.DataSizes(main_trained=table, unseen=unseen, lane_d_per_set=s1core.LANE_D_STUB))


def corpus_of(ctx: Ctx) -> tuple[str, bytes]:
    if ctx.synthetic:
        return "synthetic", SYNTHETIC_CORPUS
    if ctx.experiments_root is None:
        raise ValueError("a real run needs the experiments root")
    return "trained", p9core.load_trained_corpus(ctx.experiments_root)


def load_data(ctx: Ctx, item: dict[str, Any], *, verify: bool = True) -> tuple[data_mod.StudyData, Any]:
    """The draw of the item (regenerated by the fixed generator) checked against its manifest's stream hashes."""
    key, corpus = corpus_of(ctx)
    study = _build_data(item["seed_name"], item["seed_base"], item["table_facts"], item["unseen"], key, corpus)
    if verify:
        path = ctx.manifest_path(item)
        if path is not None:
            recorded = read_json(path)["sha256s"]
            if recorded != study.sha256s():
                raise ValueError(f"the regenerated draw {item['seed_name']} differs from the hashes in {path}")
    return study, study.seeds


@functools.cache
def _backbone(synthetic: bool, root: str | None) -> Any:
    if synthetic:
        return controls.synthetic_backbone(*PARENT)
    return controls.load_backbone(PARENT, Path(root) if root else None)[0]


def backbone_of(ctx: Ctx) -> Any:
    return _backbone(ctx.synthetic, None if ctx.experiments_root is None else str(ctx.experiments_root))


def load_model(ctx: Ctx, item: dict[str, Any], seeds: Any) -> P10S1Model:
    model = build_model(item["arm"], item["slots"], item["init_seed"], backbone_of(ctx), r1_seed=seeds.r1_codes, hash_seed=s1core.h8_seed(seeds), seed_rng=False)
    load_model_state(ctx.snapshot_dir(item), model)
    model.eval()
    return model


# --- the recorder ---------------------------------------------------------------------------------------------------------------------------------
class Recorder:
    """Per-read and per-gate files of one item, written once (never over an existing one)."""

    def __init__(self, ctx: Ctx, item: dict[str, Any]) -> None:
        self.ctx, self.item = ctx, item
        self.dir = stages_io.item_dir(ctx.run_dir, item["stage"], item["id"])

    def read_file(self, name: str) -> Path:
        return stages_io.read_path(self.ctx.run_dir, self.item["stage"], self.item["id"], name)

    def gate_file(self, name: str) -> Path:
        return self.dir / f"gate.{stages_io.safe_name(name)}.json"

    def has_read(self, name: str) -> bool:
        return self.read_file(name).is_file()

    def get_read(self, name: str) -> dict[str, Any]:
        return core.read_record(self.read_file(name), "read")

    def put_read(self, name: str, rec: dict[str, Any]) -> None:
        core.write_record(self.read_file(name), rec)

    def has_gate(self, name: str) -> bool:
        return self.gate_file(name).is_file()

    def put_gate(self, name: str, gate: dict[str, Any]) -> None:
        core.write_record(self.gate_file(name), {**core.envelope("gate"), "name": name, "gate": gate})

    def all_gates(self) -> dict[str, dict[str, Any]]:
        out: dict[str, dict[str, Any]] = {}
        for p in sorted(self.dir.glob("gate.*.json")):
            rec = core.read_record(p, "gate")
            out[str(rec["name"])] = dict(rec["gate"])
        return out

    def complete(self) -> bool:
        return (self.dir / "item.json").is_file()

    def finish(self, seconds: float, extra: dict[str, Any] | None = None) -> dict[str, Any]:
        item = self.item
        rec = {
            **core.envelope("item"), "stage": item["stage"], "cell": item["cell"], "update": item["update"], "arm": item["arm"], "facts": item["facts"], "slots": item["slots"], "draw": item["draw"], "complete": True,
            "gates": self.all_gates(), "reads_done": [r["name"] for r in item["reads"] if r["status"] == "RUN" and self.has_read(r["name"])],
            "not_applicable": [r for r in item["reads"] if r["status"] != "RUN"], "seconds": seconds, "platform": gates.platform_record(), **(extra or {}),
        }  # fmt: skip
        core.write_record(self.dir / "item.json", rec)
        return rec


# --- gate helpers ---------------------------------------------------------------------------------------------------------------------------------
def panel_counts_of(rec: dict[str, Any]) -> dict[str, dict[str, int]]:
    return {p: {k: int(rec["panels"][p][k]) for k in sealed.COUNT_KEYS} for p in sealed.PANELS}


def identity_gate(ctx: Ctx, item: dict[str, Any], plan_digest: str | None) -> dict[str, Any]:
    """Gate 1 for the checkpoint: the file hashes to ``snapshot.json``'s ``model_sha256``, to the digest in the cell's ``train.json`` and (A1) to the digest frozen in the plan."""
    snap = ctx.snapshot_dir(item)
    train_json = snap.parent.parent / "train.json"
    snap_json = snap / "snapshot.json"
    snap_sha = read_json(snap_json).get("model_sha256") if snap_json.is_file() else None
    train_sha = None
    if train_json.is_file():
        train_sha = (read_json(train_json).get("snapshot_sha256") or {}).get(str(item["update"]))
    actual = file_sha256(snap / "model.pt") if (snap / "model.pt").is_file() else None
    parts = {"snapshot_json": snap_sha, "train_json": train_sha}
    required = ["snapshot_json", "train_json"]
    if item["stage"] == core.STAGE_A1:
        parts["plan"] = plan_digest
        required.append("plan")
    ok = actual is not None and all(parts[k] == actual for k in required)
    scope = "tree" if item["arm"] == "T-OQ" else "f0"
    return gates.gate(scope, bool(ok), model_sha256=actual, agrees_with={k: (v == actual if v is not None else None) for k, v in parts.items()})


def reference_counts(ctx: Ctx, item: dict[str, Any], model: P10S1Model, data: Any, seeds: Any, kind: str) -> tuple[dict[str, dict[str, int]], dict[str, Any]]:
    """What the same checkpoint's read counts are, per P10-S1: A1 reads them from P10-S1's evaluation record through the whitelist extractor; A2 calls P10-S1's own evaluation function
    (``evaluate._read_record``) on the checkpoint (section 10: gate 2 replaced)."""
    if item["stage"] == core.STAGE_A1:
        if ctx.s1_run_dir is None:
            raise ValueError("A1 needs P10-S1's run directory")
        c = sealed.counts(ctx.s1_run_dir, item["cell"], item["update"], "ivf" if kind == "ivf" else "main")
        extra: dict[str, Any] = {"source": "P10-S1's recorded counts (eval.json, through the whitelist extractor)"}
        if kind == "ivf":
            extra["recorded_index"] = sealed.index_record(ctx.s1_run_dir, item["cell"], item["update"])
        return c, extra
    facts = item["facts"]
    if kind == "ivf":
        ivf, idx = s1eval.ivf_model(model, seeds)
        rec = s1eval._read_record(ivf, data, facts, seeds, deep=False, robustness=False)
        return {p: {k: int(rec["panels"][p][k]) for k in sealed.COUNT_KEYS} for p in sealed.PANELS}, {"source": "P10-S1's evaluation functions called from the adapter", "recorded_index": {"index_sha256": idx.sha256(), "index_lists": idx.lists}}
    rec = s1eval._read_record(model, data, facts, seeds, deep=False, robustness=False)
    return {p: {k: int(rec["panels"][p][k]) for k in sealed.COUNT_KEYS} for p in sealed.PANELS}, {"source": "P10-S1's evaluation functions called from the adapter"}


# --- a tree checkpoint ----------------------------------------------------------------------------------------------------------------------------------
def run_tree_item(ctx: Ctx, item: dict[str, Any], rec: Recorder, plan_digest: str | None) -> None:
    cfg = ctx.cfg()
    th = core.Thresholds.from_config(cfg)
    chunk = int(cfg["resources"]["eval_chunk_elements"])
    data, seeds = load_data(ctx, item)
    model = load_model(ctx, item, seeds)
    facts = int(item["facts"])
    source = model.addition
    planned = [r["name"] for r in item["reads"] if r["status"] == "RUN"]
    specs = reads.tree_read_specs(item["slots"], cfg)
    if sorted(s.name for s in specs) != sorted(planned):
        raise ValueError("the plan's reads for this item differ from the reads of this slot count")
    codes = s1eval.fact_codes(model, data, facts)
    pending = [s for s in specs if not rec.has_read(s.name)]
    stats = reads.tree_fact_pass(source, codes, specs, chunk_elements=chunk) if pending else {}
    if not rec.has_gate("checkpoint_identity"):
        rec.put_gate("checkpoint_identity", identity_gate(ctx, item, plan_digest))
    for spec in pending:
        mem = reads.TreeReadMemory(source, spec, verify=spec.name == "T0")
        began = time.monotonic()
        with reads.swapped_addition(model, mem):
            counts = reads.read_counts(model, data, facts, seeds)
        extra: dict[str, Any] = {"read_spec": {"visits": spec.visits, "prior_select": spec.prior_select, "prior_weight": spec.prior_weight}}
        if spec.name == "T0":
            extra["path_check"] = {"checked": mem.checked, "mismatched": mem.mismatched}
        rec.put_read(spec.name, reads.read_record(item["stage"], item["cell"], item["update"], spec.name, counts, facts=stats.get(spec.name), extra=extra, seconds=time.monotonic() - began))
    t0 = rec.get_read("T0")
    if not rec.has_gate("t0_path"):
        rec.put_gate("t0_path", gates.path_gate(int(t0["path_check"]["checked"]), int(t0["path_check"]["mismatched"]), cfg))
    if not rec.has_gate("t0_counts"):
        ref, extra_ref = reference_counts(ctx, item, model, data, seeds, "main")
        rec.put_gate("t0_counts", gates.counts_gate("tree", panel_counts_of(t0), ref, source=extra_ref["source"], cfg=cfg))
    if item["stage"] == core.STAGE_A1 and item["update"] == item["u_p"] and ctx.run_sealed and not rec.has_gate("tree_recall_reproduction"):
        value = s1eval.tree_recall(model, codes)  # P10-S1's own definition, on the checkpoint's own memory; consumed here, never stored or printed
        assert ctx.s1_run_dir is not None
        rec.put_gate("tree_recall_reproduction", gates.recall_gates(ctx.s1_run_dir, item["cell"], None, item["update"], tree_recall_value=value, ivf_recall_value=None, cfg=cfg)["tree_recall_reproduction"])
        del value
    if not all(rec.has_gate(n) for n in ("tv1_priors_on_against_off", "t3_against_independent_flat", "t2_against_independent_flat")):
        for name, g in gates.exactness_gates(source, codes, th, chunk_elements=chunk).items():
            rec.put_gate(name, g)


# --- a flat checkpoint ---------------------------------------------------------------------------------------------------------------------------------------
def run_flat_item(ctx: Ctx, item: dict[str, Any], rec: Recorder, plan_digest: str | None) -> None:
    cfg = ctx.cfg()
    data, seeds = load_data(ctx, item)
    model = load_model(ctx, item, seeds)
    facts, slots = int(item["facts"]), int(item["slots"])
    source = model.addition
    seeds_i64 = core.i64_seeds(cfg)
    planned = {r["name"] for r in item["reads"] if r["status"] == "RUN"}
    budgets = core.feasible_budgets(slots, cfg)
    want = {"F0", "I256@512", *(core.i64_name(c, s) for c in budgets for s in seeds_i64)}
    if planned != want:
        raise ValueError("the plan's reads for this item differ from the reads of this slot count")
    if not rec.has_gate("checkpoint_identity"):
        rec.put_gate("checkpoint_identity", identity_gate(ctx, item, plan_digest))
    codes = s1eval.fact_codes(model, data, facts)
    idx256 = s1index.build_index(source.keys.detach(), s1core.index_seed(seeds))
    idx64 = {s: s1index.build_index(source.keys.detach(), s, slots // int(cfg["reads"]["index_list_size"])) for s in seeds_i64}
    pending = [n for n in sorted(planned) if not rec.has_read(n)]
    stats: dict[str, dict[str, Any]] = {}
    if pending:
        indexes = {"I256@512": (idx256, int(cfg["reads"]["index_standard_budget"])), **{core.i64_name(c, s): (idx64[s], c) for c in budgets for s in seeds_i64}}
        stats = reads.flat_fact_pass(source, codes, indexes)

    def put(name: str, counts: dict[str, Any], seconds: float, extra: dict[str, Any] | None = None) -> None:
        rec.put_read(name, reads.read_record(item["stage"], item["cell"], item["update"], name, counts, facts=stats.get(name), extra=extra, seconds=seconds))

    if "F0" in pending:
        began = time.monotonic()
        counts = reads.read_counts(model, data, facts, seeds)
        put("F0", counts, time.monotonic() - began)
    if "I256@512" in pending:
        began = time.monotonic()
        ivf, idx = s1eval.ivf_model(model, seeds)
        counts = reads.read_counts(ivf, data, facts, seeds)
        recall = float(counts["measured"]["recall_of_exhaustive_top8"])  # P10-S1's quantity: consumed by gate 3(b) here, dropped by read_record
        ref, extra_ref = reference_counts(ctx, item, model, data, seeds, "ivf")
        same_hash = idx.sha256() == extra_ref["recorded_index"]["index_sha256"] and idx.lists == extra_ref["recorded_index"]["index_lists"]
        if not rec.has_gate("i256_counts"):
            rec.put_gate("i256_counts", gates.counts_gate("index", panel_counts_of({"panels": counts["panels"]}), ref, source=extra_ref["source"], cfg=cfg, extra_equal={"index_hash_equal": same_hash}))
        if item["stage"] == core.STAGE_A1 and ctx.run_sealed and not rec.has_gate("ivf_recall_reproduction"):
            assert ctx.s1_run_dir is not None
            rec.put_gate("ivf_recall_reproduction", gates.recall_gates(ctx.s1_run_dir, None, item["cell"], item["update"], tree_recall_value=None, ivf_recall_value=recall, cfg=cfg)["ivf_recall_reproduction"])
        del recall
        put("I256@512", counts, time.monotonic() - began, {"index_sha256": idx.sha256(), "index_lists": idx.lists})
    for c in budgets:
        for s in seeds_i64:
            name = core.i64_name(c, s)
            if name in pending:
                mem = reads.IVFBudgetMemory(source, idx64[s], c)
                began = time.monotonic()
                with reads.swapped_addition(model, mem):
                    counts = reads.read_counts(model, data, facts, seeds)
                put(name, counts, time.monotonic() - began, {"index_seed": s, "budget": c, "index_sha256": idx64[s].sha256(), "index_lists": idx64[s].lists})
    if not rec.has_gate("f0_counts"):
        ref, extra_ref = reference_counts(ctx, item, model, data, seeds, "main")
        rec.put_gate("f0_counts", gates.counts_gate("f0", panel_counts_of(rec.get_read("F0")), ref, source=extra_ref["source"], cfg=cfg))
    if not rec.has_gate("index_rebuild_i256"):
        rec.put_gate("index_rebuild_i256", gates.index_rebuild_gate(source.keys.detach(), s1core.index_seed(seeds), None, cfg))
    for s in seeds_i64:
        if not rec.has_gate(f"index_rebuild_i64_s{s}"):
            rec.put_gate(f"index_rebuild_i64_s{s}", gates.index_rebuild_gate(source.keys.detach(), s, slots // int(cfg["reads"]["index_list_size"]), cfg))


def run_item(ctx: Ctx, item: dict[str, Any], plan_digests: dict[str, str] | None = None) -> dict[str, Any]:
    """Run (or resume) one item. A completed item (``item.json`` present) is not recomputed."""
    rec = Recorder(ctx, item)
    if rec.complete():
        return core.read_record(rec.dir / "item.json", "item")
    began = time.monotonic()
    digest = (plan_digests or {}).get(f"{item['cell']}|{item['update']}")
    if item["arm"] == "T-OQ":
        run_tree_item(ctx, item, rec, digest)
    elif item["arm"] == "F-OQ":
        run_flat_item(ctx, item, rec, digest)
    else:
        raise ValueError(f"no read set for arm {item['arm']!r}")
    return rec.finish(time.monotonic() - began)


# --- gates 1 and 2 only, on the registered checkpoints (rehearsal, section 11 gate 5; R3-A9) ----------------------------------------------------------------------------------
def run_gates12_item(ctx: Ctx, item: dict[str, Any]) -> dict[str, Any]:
    """Gate 1 (the checkpoint's identity, without a frozen digest: none exists before the freeze) and gate 2 (T0 through the common path with its path check, F0, I256@512 and its index hash, against P10-S1's
    recorded counts through the whitelist extractor) for one registered checkpoint. No other read, no recall (gate 3 is not run before the freeze: the seal) and nothing is written but the result."""
    cfg = ctx.cfg()
    data, seeds = load_data(ctx, item)
    model = load_model(ctx, item, seeds)
    facts = int(item["facts"])
    result: dict[str, Any] = {"item": item["id"], "identity": identity_gate(ctx, {**item, "stage": core.STAGE_A2}, None)}  # no plan digest before the freeze
    if item["arm"] == "T-OQ":
        mem = reads.TreeReadMemory(model.addition, reads.TreeReadSpec("T0", 2, True, True), verify=True)
        with reads.swapped_addition(model, mem):
            counts = reads.read_counts(model, data, facts, seeds)
        ref, src = reference_counts(ctx, item, model, data, seeds, "main")
        result["t0_path"] = gates.path_gate(mem.checked, mem.mismatched, cfg)
        result["t0_counts"] = gates.counts_gate("tree", panel_counts_of(counts), ref, source=src["source"], cfg=cfg)
    else:
        f0 = reads.read_counts(model, data, facts, seeds)
        ref, src = reference_counts(ctx, item, model, data, seeds, "main")
        result["f0_counts"] = gates.counts_gate("f0", panel_counts_of(f0), ref, source=src["source"], cfg=cfg)
        ivf, idx = s1eval.ivf_model(model, seeds)
        c2 = reads.read_counts(ivf, data, facts, seeds)
        ref2, src2 = reference_counts(ctx, item, model, data, seeds, "ivf")
        same = idx.sha256() == src2["recorded_index"]["index_sha256"] and idx.lists == src2["recorded_index"]["index_lists"]
        result["i256_counts"] = gates.counts_gate("index", panel_counts_of({"panels": c2["panels"]}), ref2, source=src2["source"], cfg=cfg, extra_equal={"index_hash_equal": same})
    result["passed"] = all(g.get("passed") is not False for k, g in result.items() if isinstance(g, dict) and "scope" in g) and result["identity"]["passed"] is not False
    return result
