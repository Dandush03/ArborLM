# ruff: noqa: E501
"""P10IR items (ADR-0029 sections 6, 7, 11): the reads, measures and gates of one checkpoint of one cell, written read by read.

One *item* of the plan is one checkpoint (T-OQ or F-OQ) of one cell. ``run_item`` loads it, computes every read the plan lists for it (a read already on disk is not recomputed: a PAUSED stage resumes), writes
one ``read.<name>.json`` per read and one ``gate.<name>.json`` per gate, and last ``item.json`` (the completion mark). Items of one cell are run by one task so that the draw is generated once.

A1 reads P10-S1's registered checkpoints and compares T0, F0 and I256@512 with P10-S1's recorded counts through the whitelist extractor (``sealed``); stage A2 reads the bridge checkpoints and compares them
with P10-S1's own evaluation functions (``evaluate._read_record``) called here (section 10). Nothing is trained and nothing in a P10-S1 run directory is written.
"""

