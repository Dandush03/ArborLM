"""Before/after numbers for the three shortcut-gate bugs of audit 2 (AUDIT_M0_R1_2.md section 6.3), on the lineages the audit names.

"Before" is the gate as committed at 9e32b317 (read with ``git show`` and executed as a module called ``old_shortcuts``); "after" is the current
``lineages_r1_shortcuts``. Same items (``lineage_gates.sample_items``, 400 per core level), same lineages. MEASURED. Run:
``uv run --locked --offline python -m studies.m0.r1_rev4_gate_before_after`` (writes studies/m0/manifests/r1_rev4_gate_bugs.json and .md).
"""

from __future__ import annotations

import json
import subprocess
import sys
import types
from pathlib import Path

from studies.m0 import lineage_gates as lg
from studies.m0 import lineages_r1_clusters as cl
from studies.m0 import lineages_r1_shortcuts as new

ROOT = Path(__file__).resolve().parents[2]
OLD_COMMIT = "9e32b317"
CASES = (  # (lineage id, heuristic, bug)
    ("R1.temporal_critical_path", "longest_job", "(a) possessive: 'Flynn's' read as another word, the prediction discarded"),
    ("R1.order_compare", "asked_pair_stated_verbatim", "(b) direction of the stated pair ignored"),
    ("R1.minimax_tree", "smallest_number", "(c) minus sign dropped, depth counted as a number"),
)


def load_old() -> types.ModuleType:
    src = subprocess.run(["git", "show", f"{OLD_COMMIT}:studies/m0/lineages_r1_shortcuts.py"], cwd=ROOT, check=True, capture_output=True, text=True).stdout
    mod = types.ModuleType("old_shortcuts")
    mod.__dict__["__name__"] = "old_shortcuts"
    sys.modules["old_shortcuts"] = mod
    exec(compile(src, "old_shortcuts.py", "exec"), mod.__dict__)  # noqa: S102 - our own committed source
    return mod


def row(res: dict, h: str) -> dict:
    r = next(x for x in res["heuristics"] if x["heuristic"] == h)
    return {k: r[k] for k in ("accuracy", "excess_over_chance", "fires", "accuracy_when_fires", "anti_excess", "per_level_accuracy")}


def main() -> None:
    old = load_old()
    lins = {x.id: x for x in cl.registered_lineages()}
    out = []
    for lid, h, bug in CASES:
        items = lg.sample_items(lins[lid], 400, label="rev4-gate-bugs")
        b, a = row(old.run_battery(lins[lid], items), h), row(new.run_battery(lins[lid], items), h)
        out.append({"lineage": lid, "heuristic": h, "bug": bug, "n_items": len(items), "before": b, "after": a})
    d = ROOT / "studies/m0/manifests"
    (d / "r1_rev4_gate_bugs.json").write_text(json.dumps(out, indent=1, sort_keys=True) + "\n")
    lines = ["# Shortcut-gate bugs of audit 2: before and after (MEASURED, 2,000 items per lineage, same items for both)", "", f"Before = gate at {OLD_COMMIT}; after = fixed gate. Generated by `studies/m0/r1_rev4_gate_before_after.py`.", "",
             "| lineage | heuristic | bug | before: accuracy / excess / fires | after: accuracy / excess / fires |", "|---|---|---|---|---|"]
    for o in out:
        b, a = o["before"], o["after"]
        lines.append(f"| {o['lineage']} | {o['heuristic']} | {o['bug']} | {b['accuracy']} / {b['excess_over_chance']:+} / {b['fires']} | {a['accuracy']} / {a['excess_over_chance']:+} / {a['fires']} |")
    (d / "r1_rev4_gate_bugs.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
