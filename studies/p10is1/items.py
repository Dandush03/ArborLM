SYNTHETIC_CORPUS = bytes((i * 7 + 3) % 256 for i in range(p9core.CORPUS_ROW_BYTES * 64))
PARENT = p9core.PRIMARY_PARENT


@dataclass
class Ctx:
    """Where a run reads and writes. ``run_dir`` is this study's (git-ignored or outside the repository); ``experiments_root`` holds the backbone and the corpus (a real run); ``synthetic`` uses the unit tests' random
    backbone and corpus (tests and the synthetic rehearsal only)."""

    mode: str
    run_dir: Path
    experiments_root: Path | None = None
    synthetic: bool = False
    sizes: dict[str, int] = field(default_factory=lambda: {"table_facts": s1core.FACT_TABLE, "unseen": s1core.UNSEEN_FACTS})
    manifests: dict[str, Path] = field(default_factory=dict)
    config_path: Path | None = None

    def cfg(self) -> Mapping[str, Any]:
        return core.load_config(self.config_path) if self.config_path else core.cfg_of(None)

    def eval_path(self, label: str, update: int) -> Path:
        return self.run_dir / "evaluate" / label / f"u{update:08d}.json"

    def baseline_path(self, draw: int, facts: int) -> Path:
        return self.run_dir / "baselines" / f"d{draw}_f{facts}.json"


@functools.cache
def _build_data(name: str, base: int, table: int, unseen: int, corpus_key: str, corpus: bytes) -> data_mod.StudyData:
    seeds = s1core.seed_set(name, base)
    return data_mod.build_study_data(seeds, corpus, sizes=data_mod.DataSizes(main_trained=table, unseen=unseen, lane_d_per_set=s1core.LANE_D_STUB))


def corpus_of(ctx: Ctx) -> tuple[str, bytes]:
    if ctx.synthetic:
        return "synthetic", SYNTHETIC_CORPUS
    if ctx.experiments_root is None:
        raise ValueError("a real run needs the experiments root")
    return "trained", p9core.load_trained_corpus(ctx.experiments_root)


def load_data(ctx: Ctx, spec: Mapping[str, Any], *, verify: bool = True) -> tuple[data_mod.StudyData, Any]:
    """The draw of a cell (regenerated by the fixed generator), checked against its manifest's stream hashes when one is given. The seed check is made here, at the point of use."""
    adapter.assert_seed_allowed(spec.get("mode", ctx.mode), spec, ctx.cfg())
    key, corpus = corpus_of(ctx)
    study = _build_data(spec["seed_name"], spec["seed_base"], ctx.sizes["table_facts"], ctx.sizes["unseen"], key, corpus)
    path = ctx.manifests.get(spec["seed_name"])
    if verify and path is not None:
        recorded = read_json(path)["sha256s"]
        if recorded != study.sha256s():
            raise core.StageRefused(f"refused: the regenerated draw {spec['seed_name']} differs from the hashes in {path} (PAUSED — IDENTITY)")
    return study, study.seeds


@functools.cache
def _backbone(synthetic: bool, root: str | None) -> Any:
    if synthetic:
        return controls.synthetic_backbone(*PARENT)
    return controls.load_backbone(PARENT, Path(root) if root else None)[0]


def backbone_of(ctx: Ctx) -> Any:
    return _backbone(ctx.synthetic, None if ctx.experiments_root is None else str(ctx.experiments_root))


def is_environment_error(exc: BaseException) -> bool:
    """An identity or environment error (``StageRefused``, ``MemoryError``, ``OSError``) is never an item error or a gate failure: it propagates (the worker refuses, fails or is killed)."""
    return isinstance(exc, core.StageRefused | MemoryError | OSError)


# --- evaluation of one snapshot ------------------------------------------------------------------------------------------------------------------
def check_counts(read: Mapping[str, Any]) -> None:
    """Every count input is a plain integer inside [0, n] (a non-finite or impossible count is an engineering stop, never a verdict)."""
    for p, rec in read["panels"].items():
        n = int(rec["n"])
        for k in ("correct", "useful", "disabled_correct", "swap_correct", "shuffled_correct"):
            v = rec.get(k)
            if v is not None and not (isinstance(v, int) and 0 <= v <= n):
                raise ValueError(f"engineering stop: count {k}={v!r} of panel {p} is not an integer in [0, {n}]")


class LogitWatch:
    """Every logit of an evaluation is checked, not a sample: the answer-site logits are ``F.linear(final_norm(h), token.weight)`` (``evaluate.site_logits``), so a forward hook on the backbone's ``final_norm`` sees the
    input of every logit the evaluation computes (the main read, the ablations, the swap, the perturbed tables, the index read); a non-finite value there, or in the frozen output weight, is an engineering stop.
    P10-S1 itself checked the training loss, the gradient norm and the parameters at every update and the loaded state at every snapshot (``train.Trainer.step``, ``load_model_state``), and no logit at evaluation;
    this check is added here (ADR-0024 section 14). A hook is PyTorch's own API: nothing in P10-S1 is patched."""

    def __init__(self, model: Any) -> None:
        self.model, self.bad, self.seen, self.handle = model, 0, 0, None

    def __enter__(self) -> "LogitWatch":
        def hook(_m: Any, _i: Any, out: Any) -> None:
            self.seen += 1
            if not bool(torch.isfinite(out).all()):
                self.bad += 1

        self.handle = self.model.backbone.final_norm.register_forward_hook(hook)
        if not bool(torch.isfinite(self.model.backbone.token.weight).all()):
            self.bad += 1
        return self

    def __exit__(self, *exc: Any) -> None:
        if self.handle is not None:
            self.handle.remove()
        if exc[0] is None and (self.bad or self.seen == 0):
            raise ValueError(f"engineering stop: {self.bad} non-finite logit input(s) at evaluation" if self.bad else "engineering stop: the evaluation computed no logits")


def evaluate_snapshot(ctx: Ctx, spec: Mapping[str, Any], update: int, *, data: Any = None, seeds: Any = None) -> Path:
    """Evaluate one snapshot of one planned cell: the snapshot's model file must hash to the value recorded in the cell's train record; P10-S1's ``evaluate_readout`` gives the counts of both panels with the DEP
    ablations (memory off, value shuffle, address swap) and, for an F-OQ cell with a slot count above 256, the index read. Written once (an existing record is kept)."""
    path = ctx.eval_path(spec["label"], update)
    if path.is_file():
        return path
    out = adapter.cell_dir(ctx.run_dir, spec["label"])
    snap = out / "snapshots" / s1core.snapshot_stem(update)
    rec = read_json(out / adapter.TRAIN_RECORD)
    if file_sha256(snap / "model.pt") != rec["snapshot_sha256"].get(str(update)):
        raise core.StageRefused(f"refused: the snapshot {snap / 'model.pt'} does not hash to the value in its train record (PAUSED — IDENTITY)")
    if data is None:
        data, seeds = load_data(ctx, spec)
    backbone = backbone_of(ctx)
    cell = adapter.cell_of(spec, spec.get("mode", ctx.mode))
    lut = fact_lut_for(data, cell.facts) if cell.arm == "R2" else None
    model = build_model(cell.arm, cell.slots, cell.init_seed, backbone, fact_lut=lut, r1_seed=seeds.r1_codes, hash_seed=s1core.h8_seed(seeds), seed_rng=False)
    load_model_state(snap, model)
    with torch.no_grad(), LogitWatch(model):
        record = s1eval.evaluate_readout(cell, model, data, update, frozen_backbone=backbone, rows=None, deep=False, robustness=False, with_ivf=True, check_backbone=False)
    reads: dict[str, Any] = {}
    for name, read in record["reads"].items():
        check_counts(read)
        reads[name] = {"panels": read["panels"], "work": read.get("work", {}), "ivf_measured": read.get("ivf_measured", {}), "index_sha256": read.get("index_sha256"), "index_lists": read.get("index_lists")}
    core.write_record(path, {**core.envelope("eval"), "label": spec["label"], "arm": cell.arm, "facts": cell.facts, "slots": cell.slots, "draw": cell.draw, "update": update, "reads": reads, "platform": record.get("environment")})
    return path


def baseline_item(ctx: Ctx, draw: int, facts: int, spec: Mapping[str, Any], *, data: Any = None, seeds: Any = None) -> Path:
    """The no-memory baseline of a draw's fact set (P10-S1's ``baseline_record``): DEP-c's ``b`` on each panel. Written once."""
    path = ctx.baseline_path(draw, facts)
    if path.is_file():
        return path
    if data is None:
        data, seeds = load_data(ctx, spec)
    with torch.no_grad():
        rec = s1eval.baseline_record(data, backbone_of(ctx), facts, draw, s1index.first_epoch(training_stream_for(data, facts)), seeds)
    core.write_record(path, {**core.envelope("baseline"), "draw": draw, "facts": facts, "no_memory": {p: int(rec["panels"][p]["NO-MEMORY"]["correct"]) for p in core.PANELS}, "no_memory_n": {p: int(rec["panels"][p]["NO-MEMORY"]["n"]) for p in core.PANELS}})
    return path


# --- the ladder decision (section 7.2 item 6, ruling 27) --------------------------------------------------------------------------------------------------
def series_from_eval(ctx: Ctx, spec: Mapping[str, Any], upto: int, read: str = "main") -> dict[str, dict[int, L.Pt]]:
    """The cell's series per panel from its eval records at snapshots up to ``upto`` (i and a_use of the counts)."""
    out: dict[str, dict[int, L.Pt]] = {p: {} for p in core.PANELS}
    for u in spec["snapshots"]:
        if u > upto:
            continue
        p = ctx.eval_path(spec["label"], u)
        if not p.is_file():
            continue
        rec = core.read_record(p, "eval")["reads"][read]["panels"]
        for panel in core.PANELS:
            n, useful = int(rec[panel]["n"]), int(rec[panel]["useful"])
            out[panel][u] = L.Pt(core.bits(useful, n), useful / n if n else float("nan"))
    return out


def ladder_decision(ctx: Ctx, cell_specs: Sequence[Mapping[str, Any]], point: int, cfg: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """The whole cell's stop rule at ladder point ``point``: every store arm read at the cell (F-OQ, T-OQ, H8; F-OQ alone at 2K/256) is full in every replicate on both panels (two consecutive ladder points, of which
    ``point`` is the second: i*(point) - i*(point/2) <= 0.10 and i*(point/2) >= 0.473). D-OQ's fullness requests nothing. The statistic is computed from the cell's own eval records and nothing else; it is not displayed
    to anyone before the freeze. Returns ``{"point", "full": {label: bool}, "all_full": bool}``; DEP is not consulted (ruling 10)."""
    c = core.cfg_of(cfg)
    th = core.Thresholds.from_config(c)
    pts = core.ladder_points(point, c)
    prev = pts[pts.index(point) - 1] if point in pts and pts.index(point) > 0 else None
    full: dict[str, bool] = {}
    for spec in cell_specs:
        if spec["arm"] not in core.STORE_ARMS:
            continue
        ser = series_from_eval(ctx, spec, point)
        full[spec["label"]] = L.full_at_u(ser, point, prev, th)
    return {"point": point, "full": full, "all_full": bool(full) and all(full.values())}


def next_level(u0: int, granted: int, reached: int, cfg: Mapping[str, Any] | None = None) -> int | None:
    """The next ladder point to request for the whole cell: the first of the levels above U0 that is above ``reached``, within the granted length G; None when ``reached`` is G (or above)."""
    for p in core.levels_above(u0, cfg):
        if p > reached and p <= granted:
            return p
    return None


def cell_names_of(specs: Sequence[Mapping[str, Any]]) -> list[str]:
    seen: list[str] = []
    for s in specs:
        n = core.cell_name(s["facts"], s["slots"])
        if s["ladder_cell"] and n not in seen:
            seen.append(n)
    return seen


def ladder_cell_specs(specs: Sequence[Mapping[str, Any]], name: str) -> list[Mapping[str, Any]]:
    return [s for s in specs if s["ladder_cell"] and core.cell_name(s["facts"], s["slots"]) == name and s["arm"] != "R2"]


def stops_from_records(run_dir: Path, names: Sequence[str]) -> dict[str, dict[str, Any]]:
    out = {}
    for n in names:
        p = run_dir / "ladder" / f"{n.replace('/', '_')}.json"
        if p.is_file():
            out[n] = core.read_record(p, "decision")
    return out

